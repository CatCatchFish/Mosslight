from PIL import Image, ImageDraw

SIZE = 64
ORIGIN = (28, 54)
FACINGS = ("east", "south", "west", "north")


def make_view(painter, facing):
    image = Image.new("RGBA", (SIZE, SIZE))
    draw = ImageDraw.Draw(image)
    ox, oy = ORIGIN

    def rect(color, x, y, width, height):
        draw.rectangle((ox + x, oy + y, ox + x + width - 1, oy + y + height - 1), fill=color)

    def poly(color, *points):
        draw.polygon([(ox + x, oy + y) for x, y in points], fill=color)

    painter(rect, poly, "east" if facing == "west" else facing)
    if facing == "west":
        west = Image.new("RGBA", image.size)
        west.paste(image.transpose(Image.Transpose.FLIP_LEFT_RIGHT), (ox * 2 - SIZE, 0))
        return west
    return image


