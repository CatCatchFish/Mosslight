import type { Rect, Shape } from "./pixel-sprite.ts";

export function drawAxialEnemy(
  type: "slime" | "runner" | "guard",
  r: Rect,
  p: Shape,
  frame: number,
  rear: boolean,
) {
  const step = frame % 2;
  if (type === "slime") {
    const h = 16 + [0, 2, 3, 1][frame];
    p(
      "#263822",
      [-16, 1],
      [-14, -6],
      [-8, -h + 4],
      [0, -h],
      [8, -h + 4],
      [14, -6],
      [16, 1],
      [10, 5],
      [-10, 5],
    );
    p(
      "#749d47",
      [-14, -1],
      [-11, -7],
      [-6, -h + 4],
      [0, -h + 2],
      [7, -h + 5],
      [11, -7],
      [14, 1],
      [8, 3],
      [-8, 3],
    );
    p(
      rear ? "#89ab50" : "#acd36a",
      [-12, -4],
      [-8, -h + 5],
      [-2, -h + 2],
      [5, -h + 4],
      [11, -6],
      [8, 0],
      [-8, 0],
    );
    r(-5, -h + 4, 5, 2, "#d4e593");
    r(-11, -5, 2, 2, "#b4cf76");
    r(8, -3, 3, 2, "#93b65d");
    p("#d0df86", [-7, -h + 3], [-2, -h + .5], [3, -h + 1], [6, -h + 3],
      [1, -h + 2.5], [-3, -h + 4]);
    for (const [x, y] of [[-10, -5], [8, -4], [1, -h + 6]]) {
      r(x, y, 2.5, 1.5, "#79a04e");
      r(x + .5, y, 1, .75, "#dce589");
    }
    if (rear) {
      r(-4, -8, 3, 4, "#65893d");
      r(1, -12, 2, 7, "#81a94c");
      r(5, -6, 2, 3, "#668741");
    } else {
      r(-7, -6, 3, 3, "#23351d");
      r(4, -6, 3, 3, "#23351d");
      r(-6, -6, 1, 1, "#fff3ac");
      r(5, -6, 1, 1, "#fff3ac");
      r(-2, -1, 5, 1, "#516534");
    }
    return;
  }
  if (type === "runner") {
    for (let i = 0; i < 3; i++) {
      const ty = -13 + i * 5,
        shift = (i + step) % 2 ? 3 : 1;
      p(
        "#563321",
        [-7, ty],
        [-11, ty],
        [-16 - shift, ty + 4],
        [-14 - shift, ty + 5],
        [-9, ty + 3],
      );
      p(
        "#563321",
        [7, ty],
        [11, ty],
        [16 + shift, ty + 4],
        [14 + shift, ty + 5],
        [9, ty + 3],
      );
      r(-16 - shift, ty + 3, 3, 1, "#b76e49");
      r(14 + shift, ty + 3, 3, 1, "#b76e49");
    }
    p(
      "#3d2c22",
      [-12, -7],
      [-12, -19],
      [-7, -24],
      [7, -24],
      [12, -19],
      [12, -7],
      [7, 1],
      [-7, 1],
    );
    p(
      "#ac5639",
      [-11, -8],
      [-10, -19],
      [-6, -22],
      [6, -22],
      [10, -19],
      [11, -7],
      [6, -2],
      [-6, -2],
    );
    p("#e28c4d", [-10, -15], [-7, -21], [-2, -22], [-2, -8], [-8, -7]);
    p("#cc7243", [2, -22], [8, -20], [10, -15], [8, -7], [2, -8]);
    r(-1, -22, 2, 13, "#6f402c");
    r(-7, -20, 3, 1, "#f4b770");
    if (rear) {
      r(-7, -5, 14, 2, "#824432");
      r(-5, -2, 10, 2, "#b47450");
      r(-6, -23, 1, 3, "#f3bd76");
    } else {
      r(-8, -7, 16, 6, "#713e2e");
      r(-6, -6, 3, 2, "#ffe3a4");
      r(3, -6, 3, 2, "#ffe3a4");
      r(-2, -2, 4, 1, "#d68950");
      r(-11, -11 - step, 2, 8, "#de9f64");
      r(9, -11 - step, 2, 8, "#de9f64");
    }
    return;
  }
  if (type === "guard") {
    for (const x of [-15, 8]) {
      p(
        "#323c32",
        [x, -10],
        [x + 7, -10],
        [x + 8, 1 + step],
        [x + 1, 4],
        [x - 1, 1],
      );
      r(x + 1, step, 6, 2, "#818570");
    }
    p(
      "#26382f",
      [-17, -7],
      [-18, -16],
      [-12, -24],
      [-5, -28],
      [5, -28],
      [12, -24],
      [18, -16],
      [17, -7],
      [10, 0],
      [-10, 0],
    );
    p(
      "#61776a",
      [-16, -9],
      [-16, -16],
      [-11, -23],
      [-5, -27],
      [5, -27],
      [11, -23],
      [16, -16],
      [16, -9],
      [8, -4],
      [-9, -4],
    );
    p(
      "#9aa992",
      [-15, -16],
      [-10, -23],
      [-4, -26],
      [4, -26],
      [8, -23],
      [4, -20],
      [-7, -19],
    );
    p("#7e9283", [-7, -17], [0, -22], [8, -17], [12, -12], [4, -8], [-7, -9]);
    r(-10, -23, 4, 2, "#a9bd82");
    r(-12, -20, 4, 2, "#89a771");
    r(6, -13, 5, 1, "#a4b09b");
    if (rear) {
      r(-9, -7, 19, 2, "#44574e");
      r(-4, -6, 9, 3, "#a6a38a");
      r(-2, -22, 3, 10, "#51675b");
    } else {
      r(-9, -10, 18, 6, "#3d5146");
      r(-6, -9, 3, 2, "#b1eacf");
      r(3, -9, 3, 2, "#b1eacf");
      r(-4, -4, 8, 2, "#b5ad91");
    }
    return;
  }
}
